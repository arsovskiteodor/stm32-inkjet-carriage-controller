  /* USER CODE BEGIN 2 */

  DisplayInit();
  EXTI_Init();
  Sensors_Arm();

  const uint16_t speed_arr[4] = {17999, 13845, 11249, 8999};

  uint8_t sel0 = HAL_GPIO_ReadPin(GPIOG, GPIO_PIN_3);
  uint8_t sel1 = HAL_GPIO_ReadPin(GPIOG, GPIO_PIN_9);
  uint8_t speed_idx = (sel1 << 1) | sel0;

  arr = speed_arr[speed_idx];
  __HAL_TIM_SET_AUTORELOAD(&htim9, arr);
  __HAL_TIM_SET_COMPARE(&htim9, TIM_CHANNEL_2, (arr + 1) / 2);

  HAL_TIM_OC_Start(&htim9, TIM_CHANNEL_1);
  HAL_TIM_OC_Start(&htim9, TIM_CHANNEL_2);

  __HAL_TIM_SET_COUNTER(&htim3, 0);
  __HAL_TIM_CLEAR_FLAG(&htim3, TIM_FLAG_UPDATE | TIM_FLAG_CC1);
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_3);

  HAL_TIM_Base_Start(&htim2);
